def _flat(params: dict[str, object]) -> dict[str, object]:
    flat: dict[str, object] = {}
    for part in params.values():
        if isinstance(part, dict):
            for key, value in part.items():
                if isinstance(value, dict):
                    flat.update(value)
                else:
                    flat[key] = value
    return flat


