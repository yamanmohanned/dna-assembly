"""Data cards: a one-page, machine-readable and human-readable description of each genome.

A data card is built only from the cached files in data/raw (never from the network and never
from numbers typed by hand), so every value on it can be traced to a file (rule R3).
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from genomeasm.io import LoadedGenome, load_genome

CARD_SCHEMA_VERSION = 1


def build_card(loaded: LoadedGenome) -> dict[str, Any]:
    """Collect the facts about one cached genome into a JSON-serialisable dictionary."""
    genome, meta = loaded.genome, loaded.meta
    accession, _, version = genome.accession.partition(".")
    summary: dict[str, Any] = meta.get("esummary", {})
    return {
        "schema_version": CARD_SCHEMA_VERSION,
        "accession_version": genome.accession,
        "accession": accession,
        "version": int(version),
        "organism": meta.get("organism"),
        "title": meta.get("title"),
        "fasta_description": genome.description,
        "molecule_type": meta.get("moltype"),
        "topology_reported_by_ncbi": summary.get("topology"),
        "strand_reported_by_ncbi": summary.get("strand"),
        "ncbi_source_database": meta.get("source_database"),
        "ncbi_completeness": meta.get("completeness"),
        "ncbi_update_date": summary.get("updatedate"),
        "length_bp": genome.length,
        "ncbi_reported_length_bp": meta.get("ncbi_reported_length"),
        "length_matches_ncbi": genome.length == meta.get("ncbi_reported_length"),
        "base_counts": dict(genome.base_counts),
        "gc_count": genome.gc_count,
        "gc_fraction": genome.gc_fraction,
        "gc_percent": 100.0 * genome.gc_fraction,
        "non_acgt_symbols": 0,
        "lowercase_symbols_in_file": genome.n_lowercase_in_file,
        "file": loaded.fasta_path.name,
        "file_sha256": loaded.file_sha256,
        "sequence_sha256": genome.sequence_sha256,
        "downloaded_utc": meta.get("downloaded_utc"),
        "provenance": meta.get("provenance", {}),
    }


def render_card_markdown(card: dict[str, Any]) -> str:
    """Render a card as Markdown with a plain-language line for each quantity."""
    counts = card["base_counts"]
    rows = [
        ("Accession.version", card["accession_version"], "the genome's unique name at NCBI"),
        ("Organism", card["organism"], "the virus the sequence belongs to"),
        ("Title", card["title"], "NCBI's description of the record"),
        ("Molecule type", card["molecule_type"], "kind of molecule NCBI lists"),
        ("Source database", card["ncbi_source_database"], "which NCBI collection it comes from"),
        ("Completeness", card["ncbi_completeness"], "whether NCBI calls the record complete"),
        ("Topology (NCBI)", card["topology_reported_by_ncbi"], "circular or linear, as NCBI says"),
        ("Strand (NCBI)", card["strand_reported_by_ncbi"], "ss = single strand, ds = double"),
        ("Last updated at NCBI", card["ncbi_update_date"], "date of NCBI's latest edit"),
        ("Length", f"{card['length_bp']:,} bp", "how many letters the genome has"),
        ("Length reported by NCBI", f"{card['ncbi_reported_length_bp']:,} bp", "must be the same"),
        ("A / C / G / T", f"{counts['A']} / {counts['C']} / {counts['G']} / {counts['T']}", ""),
        ("GC content", f"{card['gc_percent']:.2f} %", "share of letters that are G or C"),
        ("Letters other than A, C, G, T", str(card["non_acgt_symbols"]), "must be zero"),
        ("File", f"data/raw/{card['file']}", "the saved copy that the program reads"),
        ("File SHA-256", card["file_sha256"], "fingerprint of the saved file"),
        ("Sequence SHA-256", card["sequence_sha256"], "fingerprint of the letters only"),
        ("Downloaded (UTC)", card["downloaded_utc"], "when the copy was fetched from NCBI"),
    ]
    lines = [
        f"# Data card: {card['accession_version']}",
        "",
        "Generated by `genomeasm data cards` from the cached files in `data/raw/`. "
        "Do not edit by hand.",
        "",
        "| Item | Value | Meaning |",
        "|---|---|---|",
    ]
    lines += [f"| {name} | {value} | {meaning} |" for name, value, meaning in rows]
    return "\n".join(lines) + "\n"


def write_cards(raw_dir: Path, processed_dir: Path, accessions: Iterable[str]) -> list[Path]:
    """Write ``<accession>.card.json`` and ``<accession>.card.md`` for each cached genome."""
    out = Path(processed_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for accession in accessions:
        card = build_card(load_genome(accession, raw_dir))
        json_path = out / f"{accession}.card.json"
        md_path = out / f"{accession}.card.md"
        # newline="\n": identical bytes on every operating system (Windows would add \r).
        json_text = json.dumps(card, indent=2, sort_keys=True) + "\n"
        json_path.write_text(json_text, encoding="utf-8", newline="\n")
        md_path.write_text(render_card_markdown(card), encoding="utf-8", newline="\n")
        written += [json_path, md_path]
    return written
